/** 楼梯：沿 x 起，y0→y1 展开（原 L783） */
function sw(x: number, y0: number, y1: number, dir: 1 | -1): Stair {
  return { x, y0, y1, dir };
}

/** 挑空 / 通高（原 L784） */
function vd(x0: number, y0: number, x1: number, y1: number): VoidShape {
  return { poly: rectPoly(x0, y0, x1, y1) };
}

